/**
 * Generates files.gni for the chromium-embedded release build. DDG Chromium
 * bundles that build, and GN has no glob, so it imports this list of every
 * file in the build.
 */
import fs from 'node:fs';
import path from 'node:path';

const FILES_GNI = 'files.gni';

/** GN string literals escape only backslash, double quote and dollar. */
const gnString = (s) => `"${s.replace(/[\\"$]/g, '\\$&')}"`;

/**
 * @param {string} buildDir
 * @returns {string} File contents.
 */
export function generateFilesGni(buildDir) {
    const files = fs
        .readdirSync(buildDir, { recursive: true })
        .filter((file) => file !== FILES_GNI && fs.statSync(path.join(buildDir, file)).isFile())
        .map((file) => file.split(path.sep).join('/'))
        .sort();
    return [
        '# Generated by the chromium-embedded build. Do not edit.',
        'extension_files = [',
        ...files.map((f) => `  ${gnString(f)},`),
        ']',
        '',
    ].join('\n');
}

/** @param {string} buildDir */
export function writeFilesGni(buildDir) {
    fs.writeFileSync(path.join(buildDir, FILES_GNI), generateFilesGni(buildDir));
}
